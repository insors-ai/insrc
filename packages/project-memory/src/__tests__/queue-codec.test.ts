import { test } from 'node:test';
import assert from 'node:assert/strict';
import { MemoryError } from '../errors.js';
import { decodeFrame, digest, encodeFrame, IngressBudget, snapshotCommand, snapshotJson, validateQueueLimits, visibleScope } from '../queue/codec.js';
import type { EventBody, SegmentHeader } from '../queue/types.js';
import { QUEUE_LIMITS } from '../queue/types.js';
const command = () => ({ version: 1, scope: { projectId: 'project' }, source: { producerId: 'codex', eventId: 'turn-1', sessionId: 'session', turnId: '1', sourceVersion: 'v1' }, kind: 'capture', payload: { text: 'Keep evidence', value: -0 } });
const queueId = '12345678-1234-1234-1234-123456789abc';
const fails = (fn: () => unknown, code = 'INVALID_REQUEST') => assert.throws(fn, (e: unknown) => e instanceof MemoryError && e.code === code);

test('canonical-json-frame-length-checksum-and-bounded-decoding', () => {
  assert.equal(snapshotJson({ z: ['😀', '\n', -0], a: true }, 1024).text, '{"a":true,"z":["😀","\\n",-0]}');
  const c = snapshotCommand(command(), 4096);
  const body: EventBody = { formatVersion: 1, recordType: 'event', queueId, sequence: '1', operationId: c.operationId, command: c.command, payloadHash: c.payloadHash, admittedAtMs: 100, scopeEpoch: 'epoch-1' };
  const line = encodeFrame(body, 4096);
  const parsed = JSON.parse(line.toString());
  assert.equal(parsed.bytes, Buffer.byteLength(snapshotJson(body, 8192).text));
  const restored = decodeFrame(line, 4096);
  assert.equal(restored.checksum, digest(snapshotJson(body, 8192).text));
  assert.equal(restored.body.recordType, 'event');
  assert.ok(Object.is((restored.body as EventBody).command.payload && ((restored.body as EventBody).command.payload as { value: number }).value, -0));
  assert.ok(Object.isFrozen((restored.body as EventBody).command));
  const header: SegmentHeader = { formatVersion: 1, recordType: 'segment', queueId, segmentId: '18446744073709551615', firstSequence: '18446744073709551615' };
  const headerLine = encodeFrame(header, 4096);
  assert.ok(headerLine.length <= QUEUE_LIMITS.headerBytes);
  assert.equal(decodeFrame(headerLine, 4096).body.recordType, 'segment');
  fails(() => decodeFrame(line.subarray(0, -1), 4096));
  fails(() => decodeFrame(Buffer.from(line.toString().replace('Keep evidence', 'Lose evidence')), 4096));
  fails(() => decodeFrame(Buffer.from(line.toString().replace('"bytes":', '"bytes":999999999999999999999,')), 4096));
  fails(() => decodeFrame(Buffer.concat([Buffer.from([0xff]), line]), 4096));
  fails(() => decodeFrame(Buffer.from(' ' + line), 4096));
  fails(() => decodeFrame(Buffer.alloc(8193, 10), 4096));
  const wrongVersion = { ...body, formatVersion: 2 };
  const text = snapshotJson(wrongVersion, 8192).text;
  fails(() => decodeFrame(Buffer.from(snapshotJson({ bytes: Buffer.byteLength(text), checksum: digest(text), frame: wrongVersion }, 8192).text + '\n'), 4096), 'UNSUPPORTED_VERSION');
});

test('immutable-policy-snapshot-before-persistence', () => {
  const raw = command(); const snapshot = snapshotCommand(raw, 4096);
  raw.scope.projectId = 'other'; raw.payload.text = 'changed';
  assert.equal(snapshot.command.scope.projectId, 'project');
  assert.equal((snapshot.command.payload as { text: string }).text, 'Keep evidence');
  assert.throws(() => { (snapshot.command.payload as { text: string }).text = 'mutated'; });
  let invoked = false;
  const accessor = Object.defineProperty({}, 'secret', { enumerable: true, get() { invoked = true; return 'secret'; } });
  fails(() => snapshotJson(accessor, 1024)); assert.equal(invoked, false);
  const cycle: unknown[] = []; cycle.push(cycle);
  for (const value of [cycle, new Date(), NaN, Infinity, undefined, 1n, Symbol('x'), '\ud800', '\udfff', { [Symbol('x')]: 1 }, Object.defineProperty({}, 'x', { value: 1 }), new Array(1), Object.assign([1], { extra: 2 })]) fails(() => snapshotJson(value, 4096));
  const protoKey = JSON.parse('{"__proto__":{"safe":true}}');
  const safe = snapshotJson(protoKey, 1024);
  assert.equal(Object.getPrototypeOf(safe.value), null);
  assert.equal(safe.text, '{"__proto__":{"safe":true}}');
  let deep: unknown = 1; for (let i = 0; i < 34; i++) deep = [deep];
  fails(() => snapshotJson(deep, 4096));
  fails(() => snapshotJson(Array.from({ length: 65_536 }, () => 0), 1024 * 1024));
  fails(() => snapshotJson('\u0001'.repeat(1000), 1000));
  const limits = { maxEventBytes: 4096, maxPendingBytes: 8192, segmentBytes: 4096, modelTimeoutMs: 1 };
  const budget = new IngressBudget(limits), lease = budget.reserve();
  snapshotCommand(command(), limits.maxEventBytes, lease);
  assert.ok(budget.bytes > 0); assert.equal(budget.calls, 1);
  lease.release(); lease.release(); assert.equal(budget.bytes, 0); assert.equal(budget.calls, 0);
  const held = Array.from({ length: 64 }, () => budget.reserve());
  fails(() => budget.reserve(), 'BACKPRESSURE'); held.forEach(item => item.release());
  const full = budget.reserve(); full.charge(budget.capacity);
  const second = budget.reserve(); fails(() => snapshotCommand(command(), 4096, second), 'BACKPRESSURE');
  second.release(); full.release(); assert.equal(budget.bytes, 0); assert.equal(budget.calls, 0);
  fails(() => validateQueueLimits({ ...limits, maxEventBytes: QUEUE_LIMITS.maxEventBytes + 1 }));
});

test('scoped-identity-exact-retry-and-conflicting-reuse', () => {
  const raw = command(), first = snapshotCommand(raw, 4096);
  const reordered = snapshotCommand({ payload: { value: -0, text: 'Keep evidence' }, kind: 'capture', source: { ...raw.source }, scope: { ...raw.scope }, version: 1 }, 4096);
  assert.equal(first.payloadHash, reordered.payloadHash); assert.equal(first.operationId, reordered.operationId);
  const changed = snapshotCommand({ ...raw, source: { ...raw.source, turnId: '2' } }, 4096);
  assert.equal(changed.operationId, first.operationId); assert.notEqual(changed.payloadHash, first.payloadHash);
  assert.notEqual(snapshotCommand({ ...raw, scope: { projectId: 'other' } }, 4096).operationId, first.operationId);
  assert.notEqual(snapshotCommand({ ...raw, source: { ...raw.source, producerId: 'claude' } }, 4096).operationId, first.operationId);
  assert.notEqual(snapshotCommand({ ...raw, payload: { text: 'Keep evidence', value: 0 } }, 4096).payloadHash, first.payloadHash);
  for (const value of [{ ...raw, extra: 1 }, { ...raw, scope: { projectId: '' } }, { ...raw, source: { ...raw.source, sourceVersion: 'x'.repeat(257) } }, { ...raw, expectedRevision: undefined }, { ...raw, kind: 'unknown' }]) fails(() => snapshotCommand(value, 4096));
  fails(() => snapshotCommand({ ...raw, version: 2 }, 4096), 'UNSUPPORTED_VERSION');
  assert.equal(visibleScope({ projectId: 'p', sessionId: 's' }, { projectId: 'p' }), false);
  assert.equal(visibleScope({ projectId: 'p', branch: 'main' }, { projectId: 'p', branch: 'other' }), false);
  assert.equal(visibleScope({ projectId: 'p' }, { projectId: 'p', sessionId: 's' }), true);
});
