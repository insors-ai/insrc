import { readFileSync } from 'node:fs';

const targets = ['darwin-arm64', 'darwin-x64', 'linux-x64', 'linux-arm64'];
const fields = (value, names) => value !== null && typeof value === 'object' && !Array.isArray(value) &&
	Object.keys(value).length === names.length && names.every(name => Object.hasOwn(value, name));
const requireField = (condition, name) => { if (!condition) throw new Error(`invalid Node runtime policy: ${name}`); };

/** Parse release-owned policy, never environment or remotely supplied configuration. */
export function readNodeRuntimePolicy(value) {
	requireField(fields(value, ['schemaVersion', 'nodeVersion', 'layout', 'checksums', 'targets']), 'fields');
	requireField(value.schemaVersion === 1 && /^22\.\d+\.\d+$/.test(value.nodeVersion), 'schema or Node version');
	requireField(fields(value.layout, ['node', 'npm', 'license']) && value.layout.node === 'bin/node' &&
		value.layout.npm === 'lib/node_modules/npm/bin/npm-cli.js' && value.layout.license === 'LICENSE', 'distribution layout');
	const base = `https://nodejs.org/download/release/v${value.nodeVersion}/`;
	requireField(fields(value.checksums, ['url', 'sha256', 'signerFingerprint']) &&
		value.checksums.url === `${base}SHASUMS256.txt` && /^[a-f0-9]{64}$/.test(value.checksums.sha256) &&
		/^[A-F0-9]{40}$/.test(value.checksums.signerFingerprint), 'checksum provenance');
	requireField(fields(value.targets, targets), 'target set');
	for (const target of targets) {
		const entry = value.targets[target];
		const archive = `node-v${value.nodeVersion}-${target}.tar.gz`;
		requireField(fields(entry, ['url', 'sha256', 'enabled', 'qualification']) && entry.url === `${base}${archive}` &&
			/^[a-f0-9]{64}$/.test(entry.sha256) && typeof entry.enabled === 'boolean', `archive ${target}`);
		requireField(entry.enabled ? typeof entry.qualification === 'string' &&
			/^docs\/[a-zA-Z0-9_./-]+\.md(?:#[a-zA-Z0-9_-]+)?$/.test(entry.qualification) &&
			!entry.qualification.split('/').includes('..') : entry.qualification === null, `qualification ${target}`);
		Object.freeze(entry);
	}
	Object.freeze(value.layout); Object.freeze(value.checksums); Object.freeze(value.targets);
	return Object.freeze(value);
}

export const NODE_RUNTIME_POLICY = readNodeRuntimePolicy(JSON.parse(readFileSync(
	new URL('../src/assets/node-runtime-policy.json', import.meta.url), 'utf8')));

/** Public selection has no ambient-runtime or qualification override. */
export function sourceRuntimeFor(platform, architecture) {
	const target = `${platform}-${architecture}`;
	if (!Object.hasOwn(NODE_RUNTIME_POLICY.targets, target)) throw new Error(`unsupported Node runtime target: ${target}`);
	const entry = NODE_RUNTIME_POLICY.targets[target];
	if (!entry.enabled) throw new Error(`Node runtime target is not qualified: ${target}`);
	return entry;
}

/** Shell consumers receive literal, validated release data; they need no JSON parser or Node. */
export function renderNodeRuntimeShell(policy = NODE_RUNTIME_POLICY) {
	readNodeRuntimePolicy(policy);
	const lines = ['#!/bin/sh', '# Generated by scripts/sync-node-runtime-policy.mjs. Do not edit.',
		'insrc_node_runtime_policy() {',
		`  INSRC_RUNTIME_VERSION='${policy.nodeVersion}'`,
		`  INSRC_RUNTIME_NODE='${policy.layout.node}'`,
		`  INSRC_RUNTIME_NPM='${policy.layout.npm}'`,
		'  INSRC_RUNTIME_URL= INSRC_RUNTIME_SHA256=', '  case "$1" in'];
	for (const [target, entry] of Object.entries(policy.targets)) {
		lines.push(`    ${target})`);
		if (entry.enabled) lines.push(`      INSRC_RUNTIME_URL='${entry.url}'`, `      INSRC_RUNTIME_SHA256='${entry.sha256}'`, '      ;;');
		else lines.push(`      printf '%s\\n' 'Node runtime target is not qualified: ${target}' >&2`, '      return 3 ;;');
	}
	lines.push('    *) printf \'%s\\n\' "unsupported Node runtime target: $1" >&2; return 2 ;;', '  esac', '}', '');
	return lines.join('\n');
}
