/**
 * Codegen: embed the webview's JS libraries as committed source strings.
 *
 * The chat webview runs ONE inline nonce'd <script> under a strict CSP (no CDN, no
 * remote fetch), so a library can't be <script src>'d — it must be inlined into that
 * script. esbuild bundles the EXTENSION (Node) but not the webview's runtime string,
 * so we commit the library source as a TS constant that both the dev/test toolchain
 * (tsx) and the packaged bundle (esbuild) import identically.
 *
 * The syntax highlighter (highlight.js core plus a fixed language subset) is bundled with esbuild into its
 * own module, webview-hljs.ts, imported only by the chat page.
 *
 * Regenerate after bumping `marked` or `highlight.js`: `npm run gen:webview-libs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const markedPkg = JSON.parse(readFileSync(join(here, 'node_modules/marked/package.json'), 'utf8'));
const markedSrc = readFileSync(join(here, 'node_modules/marked/marked.min.js'), 'utf8');

const out =
  `/**\n` +
  ` * GENERATED by gen-webview-libs.mjs — DO NOT EDIT. Regenerate: npm run gen:webview-libs\n` +
  ` *\n` +
  ` * marked v${markedPkg.version} (MIT) UMD, embedded as a string so the CSP-locked chat webview\n` +
  ` * (one inline nonce'd <script>, no CDN) can run it. Evaluating it in the webview defines a\n` +
  ` * global \`marked\` with \`marked.parse(md)\` -> HTML (used by render-registry, sanitized + link-\n` +
  ` * guarded before it reaches the DOM).\n` +
  ` */\n` +
  `/* eslint-disable */\n` +
  `export const MARKED_SRC: string = ${JSON.stringify(markedSrc)};\n`;

writeFileSync(join(here, 'src/chat/webview-marked.ts'), out);
console.log(`wrote src/chat/webview-marked.ts (marked v${markedPkg.version}, ${markedSrc.length} bytes)`);

// ---- the highlighter: highlight.js core + a fixed language subset, one self-contained string ----
// The languages, by highlight.js module name. xml also covers html.
const HLJS_LANGUAGES = ['typescript', 'javascript', 'json', 'python', 'go', 'java', 'scala', 'bash', 'yaml', 'css', 'xml', 'markdown', 'dockerfile', 'makefile'];
const hljsPkg = JSON.parse(readFileSync(join(here, 'node_modules/highlight.js/package.json'), 'utf8'));
const entry =
  `import hljs from 'highlight.js/lib/core';\n` +
  HLJS_LANGUAGES.map((l, i) => `import l${i} from 'highlight.js/lib/languages/${l}';\nhljs.registerLanguage('${l}', l${i});`).join('\n') +
  `\nglobalThis.hljs = hljs;\n`;
const built = await build({
  stdin: { contents: entry, resolveDir: here, loader: 'js' },
  bundle: true, minify: true, format: 'iife', platform: 'browser', target: 'es2020', write: false, legalComments: 'none',
});
let hljsSrc = built.outputFiles[0].text;
// The page is one inline <script>: a literal script tag in the library text would end it early (and break the
// shell's single-script check), so the '<' of any such text is written as \x3c, valid in a string or a regex.
hljsSrc = hljsSrc.replace(/<(\/?script)/gi, '\\x3c$1');
if (/<\/?script/i.test(hljsSrc)) throw new Error('the bundled highlighter still holds a script tag after escaping');
const HLJS_BUDGET = 250 * 1024;
if (Buffer.byteLength(hljsSrc, 'utf8') > HLJS_BUDGET) throw new Error(`the bundled highlighter is ${Buffer.byteLength(hljsSrc, 'utf8')} bytes, over the ${HLJS_BUDGET} byte budget`);

const hljsOut =
  `/**\n` +
  ` * GENERATED by gen-webview-libs.mjs — DO NOT EDIT. Regenerate: npm run gen:webview-libs\n` +
  ` *\n` +
  ` * highlight.js v${hljsPkg.version} (BSD-3-Clause) core plus ${HLJS_LANGUAGES.join(', ')}, bundled with esbuild\n` +
  ` * into one IIFE string so the CSP-locked chat webview (one inline nonce'd <script>, no CDN) can run it.\n` +
  ` * Evaluating it defines a global \`hljs\` whose highlight(code, { language }).value is span markup.\n` +
  ` * Any script-tag text in it is escaped, and the generator fails above a size budget.\n` +
  ` */\n` +
  `/* eslint-disable */\n` +
  `export const HLJS_SRC: string = ${JSON.stringify(hljsSrc)};\n`;
writeFileSync(join(here, 'src/chat/webview-hljs.ts'), hljsOut);
console.log(`wrote src/chat/webview-hljs.ts (highlight.js v${hljsPkg.version}, ${Buffer.byteLength(hljsSrc, 'utf8')} bytes of ${HLJS_BUDGET})`);
