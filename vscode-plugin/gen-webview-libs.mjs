/**
 * Codegen: embed the webview's JS libraries as committed source strings.
 *
 * The chat webview runs ONE inline nonce'd <script> under a strict CSP (no CDN, no
 * remote fetch), so a library can't be <script src>'d — it must be inlined into that
 * script. esbuild bundles the EXTENSION (Node) but not the webview's runtime string,
 * so we commit the library source as a TS constant that both the dev/test toolchain
 * (tsx) and the packaged bundle (esbuild) import identically.
 *
 * Regenerate after bumping `marked`: `npm run gen:webview-libs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const markedPkg = JSON.parse(readFileSync(join(here, 'node_modules/marked/package.json'), 'utf8'));
const markedSrc = readFileSync(join(here, 'node_modules/marked/marked.min.js'), 'utf8');

const out =
  `/**\n` +
  ` * GENERATED by gen-webview-libs.mjs — DO NOT EDIT. Regenerate: npm run gen:webview-libs\n` +
  ` *\n` +
  ` * marked v${markedPkg.version} (MIT) UMD, embedded as a string so the CSP-locked chat webview\n` +
  ` * (one inline nonce'd <script>, no CDN) can run it. Evaluating it in the webview defines a\n` +
  ` * global \`marked\` with \`marked.parse(md)\` -> HTML (used by render-registry, sanitized + link-\n` +
  ` * guarded before it reaches the DOM).\n` +
  ` */\n` +
  `/* eslint-disable */\n` +
  `export const MARKED_SRC: string = ${JSON.stringify(markedSrc)};\n`;

writeFileSync(join(here, 'src/chat/webview-marked.ts'), out);
console.log(`wrote src/chat/webview-marked.ts (marked v${markedPkg.version}, ${markedSrc.length} bytes)`);
